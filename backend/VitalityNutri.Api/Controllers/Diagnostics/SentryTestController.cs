using Microsoft.AspNetCore.Mvc;
using Sentry;

namespace VitalityNutri.Api.Controllers.Diagnostics;

/// <summary>Diagnostics endpoint to test and verify Sentry integration.</summary>
[ApiController, Route("api/test-sentry")]
[Microsoft.AspNetCore.Authorization.AllowAnonymous]
public sealed class SentryTestController : ControllerBase
{
    /// <summary>Captures a test event or message to Sentry.</summary>
    /// <param name="message">Optional custom message to send.</param>
    /// <param name="throwException">When true, throws an unhandled exception to test Sentry exception capture middleware.</param>
    /// <returns>The generated Sentry SentryId and status.</returns>
    [HttpGet]
    [HttpPost]
    public ActionResult<object> TestSentry([FromQuery] string? message, [FromQuery] bool throwException = false)
    {
        if (throwException)
        {
            throw new InvalidOperationException("This is a test exception generated by /api/test-sentry to verify Sentry exception capture.");
        }

        var text = string.IsNullOrWhiteSpace(message) ? "Hello Sentry from VitalityNutri API!" : message;
        var eventId = SentrySdk.CaptureMessage(text, SentryLevel.Info);

        return Ok(new
        {
            success = true,
            message = text,
            sentryId = eventId.ToString(),
            note = "Check your Sentry dashboard to view this event."
        });
    }
}
